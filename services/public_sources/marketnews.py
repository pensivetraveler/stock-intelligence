"""MarketNewsAPI feed (ADR 0052 §3): stock news and issuers' own press releases.

`GET https://api.marketnewsapi.com/v1/news?tickers=&category=stocks&from=&to=` with the
key in the `X-API-Key` header (never in the URL), from the first enabled MarketNewsAPI
key on the Keys screen. Times are ISO 8601 UTC to the second.

- Types `news` and `press_release` are read; `legal` notices (law-firm investigation
  announcements) are left out (`include_legal=false`).
- A press release's own text (`body`) is kept: the provider's terms let it be shown with
  attribution and a link to the original release. Publisher articles come as headline,
  snippet and summary only. The `summary` is machine-generated by the provider, so the
  stored summary is the publisher's `snippet` when there is one, and the generated
  summary is kept apart (`generated_summary`).
- A ticker matches on every exchange (MRVL is also TSXV:MRVL). Articles whose only
  listings for the ticker are on the non-US exchanges in `FOREIGN_EXCHANGES` are dropped.
- The free plan allows 50 requests a day and is delayed by 15 minutes; the delay the
  response reports is disclosed with the result.

The provider's terms allow personal and internal use, caching for a reasonable period,
and internal research and backtests; they forbid reselling or redistributing the feed or
storing the archive systematically to replace the service.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

import httpx

from services.public_sources.cache import PublicSourceCache, parse_utc, utc_text
from services.public_sources.http import RateLimiter, SourceError
from services.public_sources.news_common import NewsFeed, stored_document

NEWS_URL = "https://api.marketnewsapi.com/v1/news"
MARKETNEWS = "marketnewsapi-news"
PARSER_VERSION = "marketnewsapi-1"
REQUEST_INTERVAL = 0.1  # paid plans burst to 20 per second; the free plan counts per day
PAGE_LIMIT = 100  # the provider's maximum
MAX_PAGES = 3  # 300 articles; the free plan has only 50 requests a day
#: Exchange codes treated as non-US when they are an article's only listings of a ticker.
FOREIGN_EXCHANGES = frozenset({"TSX", "TSXV", "CSE", "NEO", "CBOE CA", "ASX", "LSE", "AIM"})


@dataclass(frozen=True)
class MarketNewsCredential:
    api_key: str = field(repr=False)

    def __repr__(self) -> str:  # never print secrets, even by accident
        return "MarketNewsCredential(<hidden>)"


def foreign_only(raw: dict[str, Any], ticker: str) -> bool:
    listings = [
        str(item.get("exchange") or "").upper()
        for item in raw.get("listings") or ()
        if str(item.get("symbol") or "").upper() == ticker
    ]
    return bool(listings) and all(code in FOREIGN_EXCHANGES for code in listings)


def parse_article(raw: dict[str, Any]) -> dict[str, Any]:
    article_type = str(raw.get("type") or "") or None
    source = raw.get("source") or {}
    publisher = str(raw.get("publisher") or source.get("name") or source.get("domain") or "")
    snippet = str(raw.get("snippet") or "")
    generated = str(raw.get("summary") or "")
    return stored_document(
        article_id=str(raw["id"]),
        headline=str(raw.get("title") or ""),
        summary=snippet,
        created_at=parse_utc(str(raw["published_at"])),
        updated_at=None,
        url=raw.get("url") or None,
        source=publisher,
        symbols=[str(s) for s in raw.get("tickers") or ()],
        article_type=article_type,
        body=str(raw.get("body") or "") if article_type == "press_release" else None,
        extra={
            "generated_summary": generated or None,
            "source_domain": str(source.get("domain") or ""),
            "listings": [
                {"symbol": str(i.get("symbol") or ""), "exchange": str(i.get("exchange") or "")}
                for i in raw.get("listings") or ()
            ],
        },
    )


class MarketNews(NewsFeed):
    source_id = MARKETNEWS
    parser_version = PARSER_VERSION
    display_name = "MarketNewsAPI"
    missing_code = "marketnews_credential_missing"

    def __init__(
        self,
        cache: PublicSourceCache,
        credential: MarketNewsCredential | None,
        client: httpx.Client,
        limiter: RateLimiter,
    ) -> None:
        super().__init__(cache, client, limiter)
        self._credential = credential

    def configured(self) -> bool:
        return self._credential is not None

    def _fetch(self, ticker: str, start: datetime, key: str) -> None:
        credential = self._credential
        if credential is None:
            raise self._missing()
        headers = {"X-API-Key": credential.api_key, "Accept": "application/json"}
        params: dict[str, str | int] = {
            "tickers": ticker,
            "category": "stocks",
            "type": "news,press_release",
            "include_legal": "false",
            "from": utc_text(start),
            "to": utc_text(self.now()),
            "sort": "published_desc",
            "limit": PAGE_LIMIT,
        }
        pages: list[bytes] = []
        cursor: str | None = None
        dropped = 0
        delays: set[int] = set()
        for _ in range(MAX_PAGES):
            query = dict(params) if cursor is None else {**params, "cursor": cursor}
            body = self._get(NEWS_URL, query, headers)
            pages.append(body)
            try:
                payload = json.loads(body)
                meta = payload.get("meta") or {}
                cursor = meta.get("next_cursor") or None
                if meta.get("delayed_minutes"):
                    delays.add(int(meta["delayed_minutes"]))
                kept = [raw for raw in payload["data"] if not foreign_only(raw, ticker)]
                dropped += len(payload["data"]) - len(kept)
                documents = [parse_article(raw) for raw in kept]
            except (ValueError, KeyError, TypeError, AttributeError) as exc:
                raise SourceError("MarketNewsAPI answered with an unexpected body") from exc
            self._store(ticker, documents)
            if cursor is None:
                break
        else:
            self.truncated = True
            self.notes.append(
                f"MarketNewsAPI had more than {MAX_PAGES * PAGE_LIMIT} articles for {ticker}; "
                "the oldest in the window were not read."
            )
        for minutes in sorted(delays):
            self.notes.append(
                f"MarketNewsAPI answered with a {minutes}-minute delay (free plan): articles "
                "from the last minutes before the download were not available."
            )
        if dropped:
            self.notes.append(
                f"{dropped} MarketNewsAPI articles listed {ticker} only on non-US exchanges "
                "and were left out."
            )
        self._cache.mark_fetched(MARKETNEWS, key, b"".join(pages))
